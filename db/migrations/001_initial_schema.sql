CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  email TEXT,
  avatar TEXT,
  roll_no TEXT,
  target_exam TEXT,
  password_hash TEXT,
  created_at TEXT NOT NULL,
  coins INTEGER DEFAULT 300,
  streak_days INTEGER DEFAULT 1,
  last_quiz_date TEXT
);

CREATE TABLE IF NOT EXISTS tests (
  id TEXT PRIMARY KEY,
  exam_id TEXT NOT NULL,
  exam_name TEXT NOT NULL,
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT,
  marks DOUBLE PRECISION NOT NULL,
  questions_count INTEGER NOT NULL,
  duration_minutes INTEGER NOT NULL,
  marks_per_correct DOUBLE PRECISION NOT NULL,
  negative_marks DOUBLE PRECISION NOT NULL,
  is_free INTEGER DEFAULT 1,
  sections_summary_json TEXT,
  test_data_json TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS test_attempts (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  test_id TEXT NOT NULL REFERENCES tests(id) ON DELETE CASCADE,
  test_title TEXT NOT NULL,
  total_questions INTEGER NOT NULL,
  score DOUBLE PRECISION NOT NULL,
  max_score DOUBLE PRECISION NOT NULL,
  correct_count INTEGER NOT NULL,
  wrong_count INTEGER NOT NULL,
  unanswered_count INTEGER NOT NULL,
  accuracy DOUBLE PRECISION NOT NULL,
  percentile DOUBLE PRECISION NOT NULL,
  estimated_air INTEGER NOT NULL,
  time_spent_seconds INTEGER NOT NULL,
  section_breakdown_json TEXT,
  responses_json TEXT,
  started_at TEXT NOT NULL,
  completed_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS paused_attempts (
  user_id TEXT NOT NULL,
  test_id TEXT NOT NULL,
  current_section_index INTEGER DEFAULT 0,
  current_question_index INTEGER DEFAULT 0,
  last_question_number INTEGER DEFAULT 1,
  section_remaining_seconds INTEGER DEFAULT 1200,
  remaining_seconds INTEGER DEFAULT 3600,
  completed_sections_json TEXT,
  responses_json TEXT,
  bookmarked_json TEXT,
  updated_at TEXT NOT NULL,
  PRIMARY KEY (user_id, test_id)
);

CREATE TABLE IF NOT EXISTS admin_audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL,
  test_id TEXT,
  details_json TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS quiz_questions (
  id TEXT PRIMARY KEY,
  subject TEXT NOT NULL,
  question_text TEXT NOT NULL,
  passage_html TEXT DEFAULT '',
  image_urls_json TEXT DEFAULT '[]',
  options_json TEXT NOT NULL,
  correct_answer TEXT NOT NULL,
  explanation_html TEXT DEFAULT '',
  marks DOUBLE PRECISION DEFAULT 1.0,
  negative_marks DOUBLE PRECISION DEFAULT 0.25,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS candidate_quiz_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  subject TEXT NOT NULL,
  question_id TEXT NOT NULL,
  attempted_at TEXT NOT NULL,
  UNIQUE(user_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_attempts_user_completed ON test_attempts(user_id, completed_at DESC);
CREATE INDEX IF NOT EXISTS idx_attempts_test ON test_attempts(test_id);
CREATE INDEX IF NOT EXISTS idx_paused_user ON paused_attempts(user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_history_user_subject ON candidate_quiz_history(user_id, subject);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_subject ON quiz_questions(subject);
